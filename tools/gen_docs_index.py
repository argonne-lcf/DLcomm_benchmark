#!/usr/bin/env python3
"""Regenerate docs/INDEX.md from the documents themselves.

The index used to be two hand-written files (`docs/fixes/00-overview.md` and
`docs/STATUS.md`). Both drifted: they listed defect counts, test counts and
collective status that stopped matching the documents they summarised. The
index is therefore generated, and the per-document headers are the single
source of truth.

Run after adding or editing a document:

    python tools/gen_docs_index.py

The script is deliberately strict about missing metadata -- it prints a warning
for any document lacking a `**Status:**` or `**Severity:**` line rather than
silently emitting a blank cell, so a header that was never filled in is
visible instead of looking intentional.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"

SEVERITY = re.compile(r"\*\*Severity:\*\*\s*([^\n]*)")
STATUS = re.compile(r"\*\*Status:\*\*\s*([^\n]*)")
JOBS = re.compile(r"\*\*Jobs?:\*\*\s*([^\n]*)")
JOBNUM = re.compile(r"\b(\d{7})\b")
TITLE = re.compile(r"^#\s+(.+)$", re.MULTILINE)


def first_sentence(text: str, limit: int = 88) -> str:
    """Collapse a field to one short cell, without inventing content."""
    text = text.strip().rstrip(".")
    text = re.sub(r"\s+", " ", text)
    for sep in (" — ", " -- "):
        if sep in text:
            text = text.split(sep)[0]
            break
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def scan(path: Path) -> dict:
    head = path.read_text(encoding="utf-8")[:1200]
    title_m = TITLE.search(head)
    title = title_m.group(1).strip() if title_m else path.stem

    # Strip the leading "Fix N — " / "Finding N — " prefix; the number is
    # already the first column.
    title = re.sub(r"^(Fix|Feature|Finding)\s+\d+\s*[—-]\s*", "", title)

    sev_m = SEVERITY.search(head)
    st_m = STATUS.search(head)
    job_m = JOBS.search(head)

    jobs = ""
    if job_m:
        nums = JOBNUM.findall(job_m.group(1))
        jobs = ", ".join(nums[:2]) + ("…" if len(nums) > 2 else "")
    if not jobs:
        nums = JOBNUM.findall(head)
        jobs = nums[0] if nums else ""

    return {
        "num": path.stem.split("-")[0],
        "file": path.name,
        "title": title,
        "severity": first_sentence(sev_m.group(1), 16) if sev_m else "",
        "status": first_sentence(st_m.group(1)) if st_m else "",
        "jobs": jobs,
        "lines": len(path.read_text(encoding="utf-8").splitlines()),
    }


def collect(kind: str) -> list[dict]:
    d = DOCS / kind
    if not d.is_dir():
        return []
    out = []
    for p in sorted(d.glob("*.md")):
        if p.name == "00-overview.md":
            continue
        out.append(scan(p))
    return out


def table(rows: list[dict], kind: str) -> list[str]:
    lines = ["| # | Document | Severity | Status | Jobs |", "|---|---|---|---|---|"]
    for r in rows:
        link = f"[{r['title']}]({kind}/{r['file']})"
        lines.append(
            f"| {r['num']} | {link} | {r['severity'] or '—'} | "
            f"{r['status'] or '—'} | {r['jobs'] or '—'} |"
        )
    return lines


def main() -> int:
    fixes = collect("fixes")
    findings = collect("findings")

    if not fixes and not findings:
        print("no documents found under docs/", file=sys.stderr)
        return 1

    out: list[str] = []
    out.append("# Documentation index")
    out.append("")
    out.append(
        "Generated by `tools/gen_docs_index.py`. Do not edit by hand; edit the "
        "document headers and regenerate."
    )
    out.append("")
    out.append(
        f"{len(fixes)} fix documents and {len(findings)} findings, "
        f"{sum(r['lines'] for r in fixes + findings)} lines total."
    )
    out.append("")
    out.append("Each fix document records one defect or feature: what was wrong, how it")
    out.append("was found, the change, and the job that exercised it. Findings record")
    out.append("measured behaviour of the platform rather than changes to this")
    out.append("repository. Job numbers are Aurora PBS job IDs.")
    out.append("")
    out.append("## Fixes and features")
    out.append("")
    out.extend(table(fixes, "fixes"))
    out.append("")
    out.append("## Findings")
    out.append("")
    out.extend(table(findings, "findings"))
    out.append("")

    (DOCS / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    missing = [r["file"] for r in fixes + findings if not r["status"]]
    print(f"wrote {DOCS / 'INDEX.md'}: {len(fixes)} fixes, {len(findings)} findings")
    if missing:
        print(f"warning: no **Status:** header in {len(missing)} file(s):")
        for m in missing:
            print(f"  {m}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
