#!/bin/bash
#PBS -N ofibuild
#PBS -A tara_deployment
#PBS -q workq
#PBS -l select=1:ngpus=4
#PBS -l walltime=02:00:00
#PBS -j oe
#PBS -o /home/kaushikvelusamy/Dynamo_Slingshot_tara/logs/

# Stage 3 only: aws-ofi-nccl against the CXI libfabric.
#
# The previous attempt failed in autogen.sh, not in the compile: rsync
# excluded .git, and m4/get_version.sh derives the version from git tags.
# The script's own documented fallback is a .release_version file at the
# top level ("allows tarballs to run autogen"), which is now present --
# this is the supported tarball path, not a patch to upstream.
set -uo pipefail

W=/home/kaushikvelusamy/Dynamo_Slingshot_tara
SRC=$W/nccl_instr_src/aws-ofi-nccl-clean
PREFIX=$W/nccl_instr
LOGD=$W/logs/ofibuild_${PBS_JOBID:-manual}
mkdir -p "$LOGD"

module load cray-mpich/9.1.0 2>/dev/null
module unload darshan 2>/dev/null

# aws-ofi-nccl >= 1.21 requires a C++20 compiler. The default g++ here is
# SUSE 7.5.0, which fails configure's C++20 probe. g++-14 is installed, so
# pin it explicitly rather than reporting the plugin as unbuildable.
export CC=$(command -v gcc-14 || command -v gcc)
export CXX=$(command -v g++-14 || command -v g++)
CUDA_HOME=${CUDA_HOME:-/opt/nvidia/hpc_sdk/Linux_aarch64/25.9/cuda/12.9}
export CUDA_HOME
FI=$W/shs-libfabric-install

# Our CXI libfabric.so itself links libcudart.so.12 (GPU-aware CXI). The
# configure link probe for fi_getinfo therefore fails with a wall of
# "undefined reference to cudaFree@libcudart.so.12" unless the CUDA runtime
# is on the link path -- which reads as "could not find a working Libfabric
# install" and is easy to misdiagnose as a broken libfabric. Supply the
# CUDA lib dir (and rpath it, so the built plugin resolves it at runtime).
CUDART_DIR=$CUDA_HOME/lib64
export LDFLAGS="-L$CUDART_DIR -Wl,-rpath,$CUDART_DIR -Wl,-rpath,$FI/lib ${LDFLAGS:-}"
export LIBS="-lcudart ${LIBS:-}"
echo "LDFLAGS: $LDFLAGS"
ls "$CUDART_DIR"/libcudart.so.12* 2>/dev/null || echo "WARN: no libcudart.so.12 in $CUDART_DIR"

echo "host: $(hostname)   ulimit -u: $(ulimit -u)"
echo "CC:  $($CC --version | head -1)"
echo "CXX: $($CXX --version | head -1)"
echo "release_version: $(cat $SRC/.release_version 2>/dev/null || echo MISSING)"
echo "libfabric: $(ls $FI/lib/libfabric.so.1.* 2>/dev/null)"
echo "nccl hdr:  $(ls $PREFIX/include/nccl.h 2>/dev/null || echo MISSING)"

cd "$SRC" || exit 1

# The tree carries state from earlier failed configure runs. Automake's
# per-directory .deps stubs are generated by config.status, and a tree that
# configured under a DIFFERENT set of enabled dirs leaves make chasing
# .deps files that were never emitted:
#   "No rule to make target '../3rd-party/efa-gda/CUDA/host/.deps/...Plo'"
# That is a stale-build-dir artifact, not a missing source. distclean puts
# the tree back to a pristine state so config.status regenerates them all.
# Pristine tree (freshly synced, no generated files), so nothing to clean.
#
# The efa_cuda_dp .Plo failure reproduces on a PRISTINE tree, so it is an
# upstream automake bug, not stale state: src/Makefile.am puts the GDAKI
# sources under `if HAVE_GDAKI`, but references them via $(top_srcdir)/...
# from a subdir with `subdir-objects`, so automake emits an unconditional
# .deps rule for a file it never generates when GDAKI is off (it is off
# here -- CXI, not EFA). --disable-dependency-tracking stops automake
# emitting those .Plo includes entirely, which is the supported escape
# hatch and costs nothing for a one-shot build.
echo "pre-configure generated files (want 0): $(find . -name 'config.status' -o -name 'config.cache' | wc -l)"

echo ""
echo "########## autogen ##########"
./autogen.sh > "$LOGD/autogen.log" 2>&1
AG=$?
echo "autogen exit: $AG"
if [ "$AG" -ne 0 ]; then
  tail -15 "$LOGD/autogen.log"
  exit 1
fi

echo ""
echo "########## configure ##########"
# Drop the cached probe result from the previous failed run, or configure
# reuses ac_cv_search_fi_getinfo=no and "fails" before testing the fix.
rm -f config.cache
./configure \
    --prefix="$PREFIX" \
    --with-libfabric="$FI" \
    --with-cuda="$CUDA_HOME" \
    --with-nccl="$PREFIX" \
    --disable-tests \
    --disable-dependency-tracking \
    > "$LOGD/configure.log" 2>&1
CF=$?
echo "configure exit: $CF"
if [ "$CF" -ne 0 ]; then
  echo "--- error context ---"
  grep -nE 'error:|cannot find|not found|No such' "$LOGD/configure.log" | tail -12
  exit 1
fi
echo "--- what configure resolved ---"
grep -iE 'libfabric|cuda|nccl' "$LOGD/configure.log" | grep -iE 'yes|no|found|using' | head -8

echo ""
echo "########## make ##########"
make -j8 > "$LOGD/make.log" 2>&1
MK=$?
echo "make exit: $MK"
if [ "$MK" -ne 0 ]; then
  grep -nE 'error:|fatal error|Error 1' "$LOGD/make.log" | head -15
  exit 1
fi
make install > "$LOGD/install.log" 2>&1
echo "install exit: $?"

echo ""
echo "########## verification ##########"
# The only question that matters: does the plugin bind to OUR CXI libfabric?
for so in $PREFIX/lib/libnccl-net*.so*; do
  [ -e "$so" ] || continue
  echo "== $so"
  ldd "$so" | grep -iE 'fabric|cudart' | head -4
done
echo ""
echo "--- fi_info providers visible to this libfabric ---"
LD_LIBRARY_PATH=$FI/lib:${LD_LIBRARY_PATH:-} $FI/bin/fi_info -l 2>/dev/null | head -8
echo ""
echo "LOGS=$LOGD"
